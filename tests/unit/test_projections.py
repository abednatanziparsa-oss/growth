class TestTodoistProjection:
    def test_provider(self) -> None:
        assert TodoistProjection().provider == "todoist"

    def test_snapshot_shape(self) -> None:
        snap = TodoistProjection().project(_plan())
        assert snap.provider == "todoist"
        assert snap.root_id is None
        assert set(snap.payload) == {"project_name", "sections", "items"}
        assert snap.payload["project_name"] == "Growth Plan"

    def test_project_name_from_plan(self) -> None:
        plan = CanonicalPlan(
            space_id=DEFAULT_SPACE_ID,
            created_at=datetime(2026, 8, 1, tzinfo=UTC),
            project_name="My Todoist Plan",
            raw_payload={"subjects": []},
        )
        snap = TodoistProjection().project(plan)
        assert snap.payload["project_name"] == "My Todoist Plan"

    def test_default_project_name(self) -> None:
        plan = CanonicalPlan(
            space_id=DEFAULT_SPACE_ID,
            created_at=datetime(2026, 8, 1, tzinfo=UTC),
        )
        snap = TodoistProjection().project(plan)
        assert snap.payload["project_name"] == "Growth Plan"
        assert snap.payload["sections"] == []
        assert snap.payload["items"] == []

    def test_sections_from_subjects_and_extra(self) -> None:
        plan = _plan(
            subjects=[
                _subject(name="Math", emoji="📘"),
                _subject(name="Physics", emoji=""),
            ],
            extra_sections=["Mistake Fix"],
        )
        snap = TodoistProjection().project(plan)
        assert snap.payload["sections"] == [
            {"name": "📘 Math"},
            {"name": "Physics"},
            {"name": "Mistake Fix"},
        ]

    def test_sections_skip_non_dict_subjects(self) -> None:
        plan = _plan(subjects=["junk", _subject(name="Real")])
        snap = TodoistProjection().project(plan)
        assert snap.payload["sections"] == [{"name": "📘 Real"}]

    def test_priority_mapping(self) -> None:
        cases = [("urgent", 4), ("high", 3), ("medium", 2), ("low", 1), ("banana", 1)]
        for priority, expected in cases:
            plan = _plan(
                subjects=[
                    _subject(name="S", priority=priority, chapters=[_chapter(name="C")])
                ]
            )
            snap = TodoistProjection().project(plan)
            assert snap.payload["items"][0]["priority"] == expected

    def test_weak_chapter_gets_max_priority(self) -> None:
        plan = _plan(
            subjects=[
                _subject(
                    name="Math",
                    priority="low",
                    chapters=[_chapter(name="Weak one", weak=True)],
                )
            ]
        )
        snap = TodoistProjection().project(plan)
        assert snap.payload["items"][0]["priority"] == 4

    def test_items_carry_subtasks(self) -> None:
        plan = _plan(
            subjects=[_subject(chapters=[_chapter(name="Algebra")])],
            standard_subtasks=["Study", "Practice"],
        )
        snap = TodoistProjection().project(plan)
        item = snap.payload["items"][0]
        assert item["content"] == "Algebra"
        assert item["section"] == "Math"
        assert item["subtasks"] == ["Study", "Practice"]

    def test_items_skip_non_dict_chapters(self) -> None:
        plan = _plan(subjects=[_subject(chapters=["junk", _chapter(name="Real")])])
        snap = TodoistProjection().project(plan)
        assert [i["content"] for i in snap.payload["items"]] == ["Real"]

    def test_items_skip_non_list_chapters(self) -> None:
        plan = _plan(subjects=[_subject(chapters="oops")])
        snap = TodoistProjection().project(plan)
        assert snap.payload["items"] == []

    def test_subtasks_not_list_ignored(self) -> None:
        plan = _plan(
            subjects=[_subject(chapters=[_chapter(name="Algebra")])],
            standard_subtasks="not-a-list",
        )
        snap = TodoistProjection().project(plan)
        assert snap.payload["items"][0]["subtasks"] == []
